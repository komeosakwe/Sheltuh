/**
 * Rasterises the brand's ü (public/brand/sheltuh-u.svg) with sharp to the
 * 1-bit bitmap the ticket email's QR PNG carries in its centre
 * (docs/design/ticket-email.md §6): black on white, its proportions kept,
 * centred in a square of QR_LOGO_MARK_MODULES (5) modules at the PNG's 16 px
 * a module (80 x 80 px), each pixel dark when it's at least half covered.
 *
 *   node --import tsx scripts/render-ticket-qr-mark.ts
 *
 * Writes lib/server/ticket-qr-mark.ts (the bits as base64), which the email
 * reads: it's bundled with the server code, and the email's QR is composited
 * synchronously when the email is built (lib/server/qr-image.ts), with no
 * file read or image library at send time. tests/ticket-qr-decode.test.ts
 * re-rasterises the SVG with sharp and checks the two still match. Rerun this
 * only when the ü or the QR's pixel size changes. Nothing is fetched.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import sharp from "sharp";
import { QR_LOGO_MARK_MODULES } from "../lib/ticket-qr";

const root = process.cwd();
/** The email PNG's pixels a module (TICKET_QR_PNG_PX_PER_MODULE in lib/server/qr-image.ts, which checks the two agree). */
const TICKET_QR_PNG_PX_PER_MODULE = 16;
const SIDE = QR_LOGO_MARK_MODULES * TICKET_QR_PNG_PX_PER_MODULE;

/** The ü's SVG, black, sized to a SIDE x SIDE box (meet: centred, proportions kept). */
export function markSvg(source: string, side: number): string {
  return source
    .replace(/fill="currentColor"/, 'fill="#000000"')
    .replace("<svg ", `<svg width="${side}" height="${side}" preserveAspectRatio="xMidYMid meet" `);
}

/** The ü rasterised by sharp, thresholded at half coverage: one byte a pixel, 1 = dark. */
export async function rasteriseMark(source: string, side: number): Promise<Uint8Array> {
  const { data, info } = await sharp(Buffer.from(markSvg(source, side)))
    .flatten({ background: "#ffffff" })
    .greyscale()
    .raw()
    .toBuffer({ resolveWithObject: true });
  if (info.width !== side || info.height !== side || info.channels !== 1) throw new Error("Unexpected raster size");
  return Uint8Array.from(data, (value) => (value < 128 ? 1 : 0));
}

/** Packs one-byte pixels 8 to a byte, most significant bit first. */
export function packBits(pixels: Uint8Array): Buffer {
  const out = Buffer.alloc(Math.ceil(pixels.length / 8));
  pixels.forEach((dark, i) => {
    if (dark) out[i >> 3] |= 0x80 >> (i & 7);
  });
  return out;
}

async function main() {
  const source = readFileSync(path.join(root, "public/brand/sheltuh-u.svg"), "utf8");
  const bits = packBits(await rasteriseMark(source, SIDE));
  const out = `// Generated by scripts/render-ticket-qr-mark.ts from public/brand/sheltuh-u.svg. Don't edit by hand.

/**
 * The ü mark for the centre of the ticket email's QR PNG: ${SIDE} x ${SIDE} px (${QR_LOGO_MARK_MODULES} modules at
 * ${TICKET_QR_PNG_PX_PER_MODULE} px), 1 bit a pixel, rows top to bottom, most significant bit first, 1 = black.
 */
export const TICKET_QR_MARK = {
  side: ${SIDE},
  bitsBase64:
    "${bits.toString("base64")}",
} as const;
`;
  writeFileSync(path.join(root, "lib/server/ticket-qr-mark.ts"), out);
  console.log(`lib/server/ticket-qr-mark.ts: ${SIDE} x ${SIDE}, ${bits.length} bytes`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(root, "scripts/render-ticket-qr-mark.ts")) {
  main().catch((error: unknown) => {
    console.error(error);
    process.exit(1);
  });
}
