/**
 * Renders the official uppercase wordmark (public/brand/sheltuh-wordmark.svg)
 * to the PNG the emails show: inline (`cid:`) in the header of the emails on
 * lib/server/email-layout.ts (the free-ticket confirmation and the onboarding
 * emails), so it shows even where remote images are blocked, and hosted from
 * public/brand in the header and footer of the emails on
 * lib/server/email-modern-layout.ts (the event reminder and the organiser
 * announcement). Email clients don't show SVG.
 *
 *   node --import tsx scripts/render-email-wordmark.ts
 *
 * Signal Orange (`SIGNAL` in lib/server/email-layout.ts, the brand's
 * --signal) on a transparent ground, at 2x a 24px-tall header (212 x 48 px).
 * No plate: the one PNG sits on two ivories (email-layout.ts's column and
 * email-modern-layout.ts's page), which a matte could match only one of, and
 * orange reads both on them and on the dark page a client that forces dark
 * mode paints behind it (a black mark on transparent vanished there, hence
 * the old opaque plate). The client blends the edges' alpha onto whatever is
 * behind.
 *
 * Writes:
 *   public/brand/sheltuh-wordmark-email.png   the image (Signal Orange on transparent, 2x)
 *   lib/server/email-wordmark.ts              the same bytes as base64, which the
 *                                             email reads (so it's bundled with
 *                                             every server function that sends mail,
 *                                             with no file read at send time)
 *
 * tests/server/email-brand.test.ts checks the two match. Rerun this only when
 * the wordmark or its email size changes. Uses Playwright's Chromium (a dev
 * dependency); nothing is fetched.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { chromium } from "@playwright/test";
import { SIGNAL } from "../lib/server/email-layout";

/** Shown size in the email, CSS pixels (the SVG's ratio is 4.41:1; brand minimum 16px tall, the nav's 24px). */
const DISPLAY_WIDTH = 106;
const DISPLAY_HEIGHT = 24;
/** Rendered at 2x for high-density screens. */
const SCALE = 2;

const root = process.cwd();
const svg = readFileSync(path.join(root, "public/brand/sheltuh-wordmark.svg"), "utf8");
const PINNED_CHROMIUM = "/opt/pw-browsers/chromium";

/** lib/server/email-wordmark.ts for these PNG bytes. */
function wordmarkModule(png: Buffer): string {
  return `// Generated by scripts/render-email-wordmark.ts from public/brand/sheltuh-wordmark.svg. Don't edit by hand.

/**
 * The uppercase wordmark in Signal Orange (${SIGNAL}) on transparent, as a PNG at ${SCALE}x
 * (${DISPLAY_WIDTH * SCALE} x ${DISPLAY_HEIGHT * SCALE} px), for the emails' header (shown at ${DISPLAY_WIDTH} x ${DISPLAY_HEIGHT}) and the modern
 * layout's footer (80 x 18).
 * Byte-for-byte public/brand/sheltuh-wordmark-email.png.
 */
export const EMAIL_WORDMARK = {
  displayWidth: ${DISPLAY_WIDTH},
  displayHeight: ${DISPLAY_HEIGHT},
  pngBase64:
    "${png.toString("base64")}",
} as const;
`;
}

async function main() {
  const browser = await chromium.launch(existsSync(PINNED_CHROMIUM) ? { executablePath: PINNED_CHROMIUM } : {});
  try {
    const page = await browser.newPage({
      viewport: { width: DISPLAY_WIDTH, height: DISPLAY_HEIGHT },
      deviceScaleFactor: SCALE,
    });
    // fill="currentColor" on the SVG: the colour comes from the page. Nothing behind it (omitBackground: transparent).
    const sized = svg.replace("<svg ", `<svg width="${DISPLAY_WIDTH}" height="${DISPLAY_HEIGHT}" `);
    await page.setContent(
      `<!DOCTYPE html><html><head><style>html,body{margin:0;padding:0;background:transparent}svg{display:block;color:${SIGNAL}}</style></head><body>${sized}</body></html>`,
    );
    const png = await page.screenshot({
      clip: { x: 0, y: 0, width: DISPLAY_WIDTH, height: DISPLAY_HEIGHT },
      omitBackground: true,
    });
    writeFileSync(path.join(root, "public/brand/sheltuh-wordmark-email.png"), png);
    writeFileSync(path.join(root, "lib/server/email-wordmark.ts"), wordmarkModule(png));
    console.log(`Wrote the ${png.length}-byte wordmark PNG (${DISPLAY_WIDTH * SCALE} x ${DISPLAY_HEIGHT * SCALE}).`);
  } finally {
    await browser.close();
  }
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
