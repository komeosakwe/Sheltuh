/**
 * Renders the official uppercase wordmark (public/brand/sheltuh-wordmark.svg)
 * to the PNG the ticket email shows in its header. Email clients don't show
 * SVG, and the email attaches the PNG inline (`cid:`) rather than linking
 * it, so it shows even where remote images are blocked.
 *
 *   node --import tsx scripts/render-email-wordmark.ts
 *
 * Black on an opaque plate of the email column's ivory (`CARD` in
 * lib/server/email-layout.ts, the colour it sits on; opaque, so it stays
 * legible where a client's dark mode darkens the page and a transparent black
 * mark would vanish), at 2x a 24px-tall header (212 x 48 px).
 *
 * Writes:
 *   public/brand/sheltuh-wordmark-email.png   the image (Black on ivory, 2x)
 *   lib/server/email-wordmark.ts              the same bytes as base64, which the
 *                                             email reads (so it's bundled with
 *                                             every server function that sends mail,
 *                                             with no file read at send time)
 *
 * tests/server/ticket-email.test.ts checks the two match. Rerun this only when
 * the wordmark or its email size changes. Uses Playwright's Chromium (a dev
 * dependency); nothing is fetched.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { chromium } from "@playwright/test";
import { CARD, INK } from "../lib/server/email-layout";

/** Shown size in the email, CSS pixels (the SVG's ratio is 4.41:1; brand minimum 16px tall, the nav's 24px). */
const DISPLAY_WIDTH = 106;
const DISPLAY_HEIGHT = 24;
/** Rendered at 2x for high-density screens. */
const SCALE = 2;

const root = process.cwd();
const svg = readFileSync(path.join(root, "public/brand/sheltuh-wordmark.svg"), "utf8");
const PINNED_CHROMIUM = "/opt/pw-browsers/chromium";

/** lib/server/email-wordmark.ts for these PNG bytes. */
function wordmarkModule(png: Buffer): string {
  return `// Generated by scripts/render-email-wordmark.ts from public/brand/sheltuh-wordmark.svg. Don't edit by hand.

/**
 * The uppercase wordmark in Black on the email column's ivory (${CARD}), as a PNG at ${SCALE}x
 * (${DISPLAY_WIDTH * SCALE} x ${DISPLAY_HEIGHT * SCALE} px), for the ticket email's header (shown at ${DISPLAY_WIDTH} x ${DISPLAY_HEIGHT}).
 * Byte-for-byte public/brand/sheltuh-wordmark-email.png.
 */
export const EMAIL_WORDMARK = {
  displayWidth: ${DISPLAY_WIDTH},
  displayHeight: ${DISPLAY_HEIGHT},
  pngBase64:
    "${png.toString("base64")}",
} as const;
`;
}

async function main() {
  const browser = await chromium.launch(existsSync(PINNED_CHROMIUM) ? { executablePath: PINNED_CHROMIUM } : {});
  try {
    const page = await browser.newPage({
      viewport: { width: DISPLAY_WIDTH, height: DISPLAY_HEIGHT },
      deviceScaleFactor: SCALE,
    });
    // fill="currentColor" on the SVG: the colour comes from the page. The opaque column ivory behind it.
    const sized = svg.replace("<svg ", `<svg width="${DISPLAY_WIDTH}" height="${DISPLAY_HEIGHT}" `);
    await page.setContent(
      `<!DOCTYPE html><html><head><style>html,body{margin:0;padding:0;background:${CARD}}svg{display:block;color:${INK}}</style></head><body>${sized}</body></html>`,
    );
    const png = await page.screenshot({
      clip: { x: 0, y: 0, width: DISPLAY_WIDTH, height: DISPLAY_HEIGHT },
    });
    writeFileSync(path.join(root, "public/brand/sheltuh-wordmark-email.png"), png);
    writeFileSync(path.join(root, "lib/server/email-wordmark.ts"), wordmarkModule(png));
    console.log(`Wrote the ${png.length}-byte wordmark PNG (${DISPLAY_WIDTH * SCALE} x ${DISPLAY_HEIGHT * SCALE}).`);
  } finally {
    await browser.close();
  }
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
